def coverage(pattern, exams):
    expression = re.compile(pattern)
    found = []
    for exam in exams:
        hits = [record for record in exam["records"]
                if record["phase"] in ("vocabulary", "grammar", "reading", "listening")
                and (record["phase"] != "listening" or record["listening_actual"])
                and expression.search(record["text"])]
        if hits:
            found.append({"exam": exam["id"], "hits": hits})
    return found


def table(entries, first=False):
    if first:
        lines = ["| 单词 | 读音 | 中文核心义 | 常用搭配与中文 |",
                 "| --- | --- | --- | --- |"]
    else:
        lines = ["| 单词 | 读音 | 中文核心义 | 常用搭配与中文 | 检出套数 |",
                 "| --- | --- | --- | --- | ---: |"]
    for item in entries:
        word = item["word"] + ("（补充）" if item["priority"] == "易混和场景补充" else "")
        cells = [word, item["reading"], item["meaning"],
                 item["collocation"] + "（" + item["translation"] + "）"]
        if not first:
            hit = item["occurrences"][0]
            page = hit["hits"][0]["page"]
            target = f"../markdown/{hit['exam']}/{hit['exam']}.md#page-{page:02d}"
            cells.append(f"[{item['document_count']}/29]({target})")
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


